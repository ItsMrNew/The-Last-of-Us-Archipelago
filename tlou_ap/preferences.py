"""Local runtime preferences are separate from immutable AP slot configuration."""
import json

from .catalog import Config, GAME

DEFAULT_RUNTIME = {'death_link': 'yaml', 'airhorn_mode': 'yaml', 'airhorn_duration': 60}
DEFAULT_SEED = {'starting_chapters': 2, 'mission_checks': True, 'chapter_checks': True,
                'collectible_checks': True, 'death_link': False, 'airhorn_trap_percentage': 10,
                'airhorn_mode': 'single_blast', 'airhorn_duration': 60,
                'resource_supplies': True, 'shaky_hands_percentage': 0, 'faulty_flashlight_percentage': 0}


def validate_runtime(value):
    if not isinstance(value, dict):
        raise ValueError('Invalid gameplay preferences')
    result = {**DEFAULT_RUNTIME, **value}
    if (set(result) != set(DEFAULT_RUNTIME) or result['death_link'] not in ('yaml', 'enabled', 'disabled')
            or result['airhorn_mode'] not in ('yaml', 'single_blast', 'timed')
            or type(result['airhorn_duration']) is not int or not 30 <= result['airhorn_duration'] <= 120):
        raise ValueError('Invalid gameplay preferences')
    return result


def death_enabled(preferences, config):
    choice = preferences['death_link']
    return config.death_link if choice == 'yaml' else choice == 'enabled'


def seed_yaml(name, values):
    if not isinstance(values, dict) or set(values) != set(DEFAULT_SEED):
        raise ValueError('Invalid seed settings')
    Config(**values)
    if not name.strip():
        raise ValueError('Enter a slot name')
    lines = [f'name: {json.dumps(name.strip(), ensure_ascii=False)}', f'game: {GAME}',
             'description: Generated by the TLOU Archipelago client.', f'{GAME}:',
             '  progression_balancing: 50', '  accessibility: full']
    for key, value in values.items():
        lines.append(f'  {key}: {str(value).lower() if type(value) is bool else value}')
    return '\n'.join(lines) + '\n'
